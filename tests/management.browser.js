  await modal.locator('[name="name"]').fill(longName);
  await modal.getByRole('button',{name:'Сохранить изменения',exact:true}).click();
  check((await page.locator('.catalog-copy strong').innerText())===longName,'Model can be renamed');
  check(await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth),'Long catalog name does not overflow');
  await page.getByRole('button',{name:'Новая модель',exact:true}).click();
  await modal.locator('[name="name"]').fill(longName.toLowerCase());
  await modal.getByRole('button',{name:'Добавить модель',exact:true}).click();
  check((await modal.locator('.form-error').innerText()).includes('уже существует'),'Duplicate model name rejected');
  await page.keyboard.press('Escape');
  await page.screenshot({path:'output/playwright/models-management.png',fullPage:true});
  await nav.getByRole('button',{name:'Настройки',exact:true}).click();
  const downloadEvent=page.waitForEvent('download');
  await page.getByRole('button',{name:'Скачать копию',exact:true}).click();
  const download=await downloadEvent;
  await download.saveAs('output/playwright/management-backup.json');
  check(download.suggestedFilename().endsWith('.json'),'Backup export works');
  await nav.getByRole('button',{name:'Склад',exact:true}).click();
  await page.locator('.workspace-tabs button').filter({hasText:'Модели'}).click();
  await page.getByRole('button',{name:`Удалить модель ${longName}`,exact:true}).click();
  check((await modal.innerText()).includes('операциями (1)'),'Model deletion explains linked records');
  await modal.getByRole('button',{name:'Удалить модель и операции',exact:true}).click();
